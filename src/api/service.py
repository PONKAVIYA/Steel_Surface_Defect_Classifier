"""Small local HTTP API so the ECE acquisition system (or any client) can submit images.

Run:   uvicorn src.api.service:app --host 127.0.0.1 --port 8000
Docs:  http://127.0.0.1:8000/docs  (OpenAPI schema generated by FastAPI)

Endpoints
  GET  /v1/health    liveness + whether a trained model is loaded
  GET  /v1/model     model version, input size, review threshold
  POST /v1/inspect   multipart: file=<image>, device_id, source=hardware|simulated_hardware|upload,
                     operator_note, save=true|false  ->  inspection result JSON
Errors use one shape: {"error": {"code": "...", "message": "..."}} with an appropriate HTTP status.
"""
from __future__ import annotations

import os
from typing import Literal

from fastapi import FastAPI, File, Form, UploadFile
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field

from src.config import load_config, resolve_path
from src.data.preprocessing import ImageLoadError
from src.database.db import DatabaseError
from src.database.repository import InspectionRepository
from src.hardware.interface import build_result_message
from src.inference.predictor import ModelUnavailableError, Predictor
from src.inference.service import InspectionService
from src.utils.logging_config import get_logger, setup_logging

log = get_logger("api")


class ErrorBody(BaseModel):
    code: str
    message: str


class ErrorResponse(BaseModel):
    error: ErrorBody


class HealthResponse(BaseModel):
    status: Literal["ok"]
    model_loaded: bool
    model_error: str | None = None


class InspectResponse(BaseModel):
    message_version: str
    status: Literal["ok"]
    inspection_id: str
    is_model_prediction: bool = Field(True, description="Always true: this is a model prediction, not a diagnosis")
    predicted_class: str
    predicted_display_name: str
    confidence: float = Field(description="Top softmax score; not a calibrated probability of correctness")
    probabilities: dict[str, float]
    review_needed: bool
    review_threshold: float | None
    image_quality_ok: bool
    quality_warnings: list[str]
    model_version: str
    inference_ms: float
    saved: bool
    simulated: bool
    device_id: str | None


def _error(status: int, code: str, message: str) -> JSONResponse:
    return JSONResponse(status_code=status, content={"error": {"code": code, "message": message}})


def create_app(cfg: dict | None = None, predictor: Predictor | None = None,
               repository: InspectionRepository | None = None, load_model: bool = True) -> FastAPI:
    setup_logging()
    cfg = cfg or load_config()
    model_error = None
    if predictor is None and load_model:
        try:
            predictor = Predictor.from_checkpoint(resolve_path(cfg["inference"]["model_path"]),
                                                  cfg["inference"].get("review_threshold"))
        except ModelUnavailableError as exc:
            model_error = str(exc)
            log.warning("API started without a model: %s", exc)
    if repository is None:
        repository = InspectionRepository(resolve_path(cfg["paths"]["inspections_dir"]))
    service = InspectionService(cfg, predictor, repository)
    max_bytes = int(float(cfg["quality"].get("max_upload_mb", 10)) * 1024 * 1024)

    app = FastAPI(title="Steel Surface Defect Classifier API", version="1.0",
                  description="Local inspection API. Results are model predictions, not engineering diagnoses.")
    app.state.service = service

    @app.get("/v1/health", response_model=HealthResponse)
    def health():
        return {"status": "ok", "model_loaded": service.model_available, "model_error": model_error}

    @app.get("/v1/model", responses={503: {"model": ErrorResponse}})
    def model_info():
        if not service.model_available:
            return _error(503, "MODEL_UNAVAILABLE", model_error or "No trained model loaded.")
        return service.predictor.info()

    @app.post("/v1/inspect", response_model=InspectResponse,
              responses={400: {"model": ErrorResponse}, 413: {"model": ErrorResponse},
                         415: {"model": ErrorResponse}, 422: {"model": ErrorResponse},
                         500: {"model": ErrorResponse}, 503: {"model": ErrorResponse}})
    async def inspect(file: UploadFile = File(...), device_id: str | None = Form(None),
                      source: str = Form("hardware"), operator_note: str = Form(""), save: bool = Form(True)):
        if source not in ("hardware", "simulated_hardware", "upload"):
            return _error(422, "INVALID_SOURCE", "source must be hardware, simulated_hardware or upload")
        if not service.model_available:
            return _error(503, "MODEL_UNAVAILABLE",
                          (model_error or "No trained model loaded.") + " No prediction was made.")
        data = await file.read(max_bytes + 1)
        if len(data) > max_bytes:
            return _error(413, "FILE_TOO_LARGE", f"Image exceeds {max_bytes // (1024 * 1024)} MB")
        if not data:
            return _error(400, "EMPTY_FILE", "The uploaded file is empty")
        try:
            outcome = service.inspect(data, source, file.filename, device_id, explain=False)
        except ImageLoadError as exc:
            code = 415 if "Unsupported image format" in str(exc) else 400
            return _error(code, "UNSUPPORTED_FORMAT" if code == 415 else "IMAGE_DECODE_ERROR", str(exc))
        if save:
            try:
                service.save(outcome, operator_note)
            except DatabaseError as exc:
                log.error("Saving inspection failed: %s", exc)
                return _error(500, "DATABASE_ERROR", f"Prediction made but not saved: {exc}")
        summary = outcome.summary()
        msg = build_result_message(summary)
        msg.update({"probabilities": summary["probabilities"], "review_threshold": summary["review_threshold"],
                    "inference_ms": summary["inference_ms"], "saved": outcome.saved})
        return msg

    return app


# Module-level app for `uvicorn src.api.service:app`. Tests set STEEL_API_NO_AUTOLOAD=1 and call
# create_app() with temporary storage instead.
app = None if os.environ.get("STEEL_API_NO_AUTOLOAD") else create_app()
